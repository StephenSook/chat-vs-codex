import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, expect, it } from "vitest";
import {
  deriveSeason,
  parseViewerSeason,
  type SeasonReceipt,
  seasonLine,
} from "../src/season.js";
import { loadSeason, recordSeason } from "../src/season-store.js";
import { startRoundServer } from "../src/server.js";

function receipt(
  roundId: string,
  overrides: Partial<SeasonReceipt> = {},
): SeasonReceipt {
  return {
    roundId,
    mode: "live-twitch",
    winner: "codex",
    autopsy: null,
    events: [],
    ...overrides,
  };
}

it("separates fixture and broadcaster-test winners from viewer results and counts only declared winners", () => {
  const season = deriveSeason([
    receipt("viewer-chat", { winner: "chat", input: "chat" }),
    receipt("viewer-codex", { input: "raid" }),
    receipt("viewer-unawarded", { winner: null }),
    receipt("test-broadcaster", {
      trigger: "broadcaster-test",
      input: "channel-points",
    }),
    receipt("test-fixture", { mode: "local-fixture" }),
    receipt("test-event", {
      events: [
        {
          type: "round.state",
          trigger: "broadcaster-test",
          sequence: 1,
          atMs: 0,
          wallTime: "2026-10-31T00:00:00.000Z",
        },
      ],
    }),
  ]);
  expect(season.viewers).toEqual({
    rounds: 3,
    chatWins: 1,
    codexWins: 1,
    unawarded: 1,
    byInput: {
      chat: 1,
      "channel-points": 0,
      whisper: 0,
      raid: 1,
      "power-up": 0,
      unknown: 1,
    },
  });
  expect(season.tests).toMatchObject({
    rounds: 3,
    codexWins: 3,
    fixtures: 1,
    broadcasterTests: 2,
  });
  expect(seasonLine(season.viewers)).toBe("SEASON · CHAT 1 : CODEX 1");
});

it("never infers unrecorded historical inputs and rejects duplicate rounds", () => {
  const row = receipt("historical");
  expect(deriveSeason([row]).viewers.byInput.unknown).toBe(1);
  expect(deriveSeason([row]).viewers.byInput.chat).toBe(0);
  expect(() => deriveSeason([row, row])).toThrow("Duplicate season round");
});

it("counts all five declared input paths and produces a deterministic order", () => {
  const inputs = [
    "chat",
    "channel-points",
    "whisper",
    "raid",
    "power-up",
  ] as const;
  const rows = inputs.map((input) => receipt(input, { input }));
  const normal = deriveSeason(rows);
  expect(deriveSeason([...rows].reverse())).toEqual(normal);
  for (const input of inputs) expect(normal.viewers.byInput[input]).toBe(1);
  expect(normal.roundIds).toEqual([...inputs].sort());
});

it("refuses malformed or inconsistent viewer totals at the browser boundary", () => {
  const valid = deriveSeason([receipt("one", { input: "chat" })]).viewers;
  expect(parseViewerSeason(valid)).toEqual(valid);
  for (const value of [
    null,
    {},
    { ...valid, rounds: -1 },
    { ...valid, codexWins: 0 },
    { ...valid, byInput: { ...valid.byInput, chat: 2 } },
    { ...valid, rounds: 1.5 },
  ])
    expect(() => parseViewerSeason(value)).toThrow("Invalid viewer season");
});

const directories: string[] = [];
afterEach(async () => {
  for (const directory of directories.splice(0))
    await rm(directory, { recursive: true, force: true });
});
it("checks exact generated bytes and catches a new, untracked receipt before commit", async () => {
  const root = await mkdtemp(join(tmpdir(), "season-check-"));
  directories.push(root);
  await mkdir(join(root, "docs/rounds"), { recursive: true });
  await recordSeason(root, false);
  await expect(recordSeason(root, true)).resolves.toMatchObject({
    viewers: { rounds: 0 },
  });
  const roundId = "00000000-0000-4000-8000-000000000001";
  await writeFile(
    join(root, "docs/rounds", `${roundId}.json`),
    JSON.stringify({
      schemaVersion: 1,
      ...receipt(roundId, { input: "whisper", winner: "chat" }),
    }),
  );
  await expect(recordSeason(root, true)).rejects.toThrow(
    "Season receipt is stale",
  );
  await recordSeason(root, false);
  expect(
    JSON.parse(await readFile(join(root, "docs/season.json"), "utf8")).viewers
      .chatWins,
  ).toBe(1);
  await expect(recordSeason(root, true)).resolves.toMatchObject({
    viewers: { rounds: 1 },
  });
  await writeFile(join(root, "docs/rounds", `${roundId}.json`), "{}");
  await expect(loadSeason(join(root, "docs/rounds"))).rejects.toThrow(
    "Invalid season receipt",
  );
});

it("serves only viewer totals on connect and publishes actual receipt updates without replaying round activity", async () => {
  const first = deriveSeason([
    receipt("test", { trigger: "broadcaster-test" }),
  ]).viewers;
  const running = await startRoundServer({ season: first });
  const controller = new AbortController();
  try {
    expect(new URL(running.origin).port).not.toBe("4317");
    const response = await fetch(`${running.origin}/api/events`, {
      signal: controller.signal,
    });
    const reader = response.body?.getReader();
    if (!reader) throw new Error("Missing season SSE");
    const start = new TextDecoder().decode((await reader.read()).value);
    expect(start).toContain(`event: season\ndata: ${JSON.stringify(first)}`);
    expect(start).not.toContain("broadcasterTests");
    const updated = deriveSeason([
      receipt("viewer", { winner: "chat", input: "chat" }),
    ]).viewers;
    running.updateSeason(updated);
    const message = new TextDecoder().decode((await reader.read()).value);
    expect(message).toContain(
      `event: season\ndata: ${JSON.stringify(updated)}`,
    );
    expect(message).not.toContain("event: round");
    controller.abort();
  } finally {
    controller.abort();
    await running.close();
  }
});
